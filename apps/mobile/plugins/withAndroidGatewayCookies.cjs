const fs = require("node:fs");
const path = require("node:path");
const { withDangerousMod, withMainApplication } = require("expo/config-plugins");

// skofo: expo-image's Glide client comes from OkHttpClientProvider.createClient(), whose jar is
// empty (and expo-app-metrics replaces the factory), so images behind the sign-in gateway got the
// login page. Install, after the Expo lifecycle listeners, a factory backed by the WebView cookies.

const FACTORY_CLASS = "GatewayCookieClientFactory";

function factorySource(packageName, { appMetrics = false } = {}) {
  const metricsImports = appMetrics
    ? `import expo.modules.appmetrics.networkrequests.NetworkRequestEventListener
import expo.modules.appmetrics.networkrequests.NetworkRequestInterceptor
`
    : "";
  // expo-app-metrics installs its own factory from its lifecycle listener; ours replaces it, so
  // keep its observer on our clients.
  const metricsBuilder = appMetrics
    ? `
      .addInterceptor(NetworkRequestInterceptor.instance)
      .eventListenerFactory(NetworkRequestEventListener.factory)`
    : "";
  return `package ${packageName}

import com.facebook.react.modules.network.ForwardingCookieHandler
import com.facebook.react.modules.network.OkHttpClientFactory
import com.facebook.react.modules.network.OkHttpClientProvider
import com.facebook.react.modules.network.ReactCookieJarContainer
${metricsImports}import java.net.CookieHandler
import okhttp3.Interceptor
import okhttp3.JavaNetCookieJar
import okhttp3.OkHttpClient
import okhttp3.Response
import okhttp3.ResponseBody.Companion.toResponseBody

/**
 * Every OkHttp client React Native hands out (fetch, WebSocket, expo/fetch, expo-image's Glide
 * loader) reads the WebView cookie store, so a sign-in gateway's session cookie also reaches
 * image and media requests. The jar stays a ReactCookieJarContainer because NetworkingModule and
 * expo/fetch replace its contents. Generated by plugins/withAndroidGatewayCookies.cjs.
 */
class ${FACTORY_CLASS} : OkHttpClientFactory {
  override fun createNewNetworkModuleClient(): OkHttpClient {
    val cookieJar = ReactCookieJarContainer()
    cookieJar.setCookieJar(JavaNetCookieJar(ForwardingCookieHandler()))
    return OkHttpClientProvider.createClientBuilder()
      .cookieJar(cookieJar)
      .addInterceptor(GatewayAssetRedirectInterceptor)${metricsBuilder}
      .build()
  }

  companion object {
    /** Call from Application.onCreate() after the Expo lifecycle listeners have run. */
    fun install() {
      OkHttpClientProvider.setOkHttpClientFactory(${FACTORY_CLASS}())
      // HttpURLConnection users (Android media) read cookies from the JVM default handler.
      CookieHandler.setDefault(ForwardingCookieHandler())
    }
  }
}

/**
 * When the gateway session has expired, an asset request is redirected to the sign-in page and
 * would come back as HTML with status 200, which Glide then caches under the image's key. Turn
 * that into a 401 so nothing is cached and the image loads once the user signs in again.
 */
private object GatewayAssetRedirectInterceptor : Interceptor {
  override fun intercept(chain: Interceptor.Chain): Response {
    val request = chain.request()
    val response = chain.proceed(request)
    val redirectedAway = response.request.url.host != request.url.host
    if (!redirectedAway || !request.url.encodedPath.contains("/api/assets/")) return response
    response.close()
    return Response.Builder()
      .request(request)
      .protocol(response.protocol)
      .code(401)
      .message("Gateway sign-in required")
      .body("".toResponseBody(null))
      .build()
  }
}
`;
}

const REGISTRATION = `\n    ${FACTORY_CLASS}.install()`;

function registerFactory(contents) {
  if (contents.includes(`${FACTORY_CLASS}.install()`)) return contents;
  // After the Expo lifecycle listeners: expo-app-metrics sets its own factory there.
  const anchor = "ApplicationLifecycleDispatcher.onApplicationCreate(this)";
  const index = contents.indexOf(anchor);
  if (index === -1) {
    throw new Error(
      "withAndroidGatewayCookies: could not find ApplicationLifecycleDispatcher.onApplicationCreate(this) in MainApplication — the Expo template changed; update the plugin anchor.",
    );
  }
  const end = index + anchor.length;
  return contents.slice(0, end) + REGISTRATION + contents.slice(end);
}

function hasPackage(name, projectRoot) {
  try {
    require.resolve(`${name}/package.json`, { paths: [projectRoot] });
    return true;
  } catch {
    return false;
  }
}

module.exports = function withAndroidGatewayCookies(config) {
  const packageName = config.android?.package;
  if (!packageName) throw new Error("withAndroidGatewayCookies: android.package is required.");

  config = withMainApplication(config, (nextConfig) => {
    if (nextConfig.modResults.language !== "kt") {
      throw new Error("withAndroidGatewayCookies: MainApplication must be Kotlin.");
    }
    nextConfig.modResults.contents = registerFactory(nextConfig.modResults.contents);
    return nextConfig;
  });

  return withDangerousMod(config, [
    "android",
    (nextConfig) => {
      const directory = path.join(
        nextConfig.modRequest.platformProjectRoot,
        "app/src/main/java",
        ...packageName.split("."),
      );
      fs.mkdirSync(directory, { recursive: true });
      fs.writeFileSync(
        path.join(directory, `${FACTORY_CLASS}.kt`),
        factorySource(packageName, {
          appMetrics: hasPackage("expo-app-metrics", nextConfig.modRequest.projectRoot),
        }),
      );
      return nextConfig;
    },
  ]);
};

module.exports.registerFactory = registerFactory;
module.exports.factorySource = factorySource;
